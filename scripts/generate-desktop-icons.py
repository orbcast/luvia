#!/usr/bin/env python3
"""Generate desktop's embedded Solar SVG data from the shared masters."""
from pathlib import Path
import json
import subprocess

ICONS = (
    ("home", "linear"),
    ("home", "bold"),
    ("clapperboard", "linear"),
    ("clapperboard", "bold"),
    ("heart", "linear"),
    ("heart", "bold"),
    ("magnifer", "linear"),
    ("magnifer", "bold"),
    ("settings", "linear"),
    ("settings", "bold"),
    ("play", "bold"),
    ("info-circle", "linear"),
    ("bookmark", "linear"),
    ("alt-arrow-right", "linear"),
    ("alt-arrow-down", "linear"),
    ("list", "linear"),
    ("alt-arrow-left", "linear"),
    ("calendar", "linear"),
    ("fire", "linear"),
    ("map-point", "linear"),
    ("users-group-rounded", "linear"),
    ("chat-round", "linear"),
    ("clock-circle", "linear"),
    ("volume-loud", "linear"),
    ("volume-cross", "linear"),
    ("share", "linear"),
    ("screencast", "linear"),
    ("full-screen", "linear"),
    ("skip-next", "linear"),
    ("skip-previous", "linear"),
    ("rewind-10-seconds-back", "linear"),
    ("rewind-10-seconds-forward", "linear"),
    ("close", "linear"),
    ("minus", "linear"),
    ("close-circle", "linear"),
    ("widget-2", "linear"),
    ("pause", "bold"),
    ("subtitles", "linear"),
    ("playlist", "linear"),
    ("document-text", "linear"),
    ("bookmark", "bold"),
)

OUTPUT = "apps/desktop/internal/icons/icons_gen.go"


def render(source: Path) -> str:
    lines = ["// Code generated by scripts/generate-desktop-icons.py; DO NOT EDIT.",
             "// Solar icons by 480 Design, CC BY 4.0; see assets/ui-icons/solar/manifest.json.",
             "package icons", "", "// Sources holds every embedded SVG by its figure name.",
             "var Sources = map[string]string{"]
    for name, style in ICONS:
        svg = (source / f"solar--{name}-{style}.svg").read_text(encoding="utf-8")
        key = f"{name}-{style}"
        lines.append(f"\t{json.dumps(key)}: " + json.dumps(svg) + ",")
    return "\n".join(lines + ["}", ""])


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    target = root / OUTPUT
    target.write_text(render(root / "assets/ui-icons/solar"), encoding="utf-8")
    # gofmt aligns the map values; running it here keeps the generator's
    # output identical to what the repository commits.
    subprocess.run(["gofmt", "-w", str(target)], check=True)


if __name__ == "__main__":
    main()
