#!/usr/bin/env python3
"""Generate desktop's embedded Solar SVG data from the shared masters."""
from pathlib import Path
import json

ICONS = ("home", "clapperboard", "heart", "magnifer", "tuning")


def render(source: Path) -> str:
    lines = ["// Code generated by scripts/generate-desktop-icons.py; DO NOT EDIT.",
             "// Solar icons by 480 Design, CC BY 4.0; see assets/ui-icons/solar/manifest.json.",
             "package appshell", "", "var solarSources = [...]string{"]
    for name in ICONS:
        svg = (source / f"solar--{name}-linear.svg").read_text(encoding="utf-8")
        lines.append("\t" + json.dumps(svg, ensure_ascii=True) + ",")
    return "\n".join(lines + ["}", ""])


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    (root / "apps/desktop/internal/appshell/icons_gen.go").write_text(
        render(root / "assets/ui-icons/solar"), encoding="utf-8")


if __name__ == "__main__":
    main()
